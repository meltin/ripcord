/// A private pasteboard, so tests never touch what the user has copied.
private func withPasteboard<T>(_ body: (NSPasteboard) throws -> T) rethrows -> T {
  let pasteboard = NSPasteboard.withUniqueName()
  defer { pasteboard.releaseGlobally() }
  return try body(pasteboard)
}

private func png(width: Int, height: Int) throws -> Data {
  let rep = try #require(
    NSBitmapImageRep(
      bitmapDataPlanes: nil, pixelsWide: width, pixelsHigh: height, bitsPerSample: 8,
      samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
      bytesPerRow: 0, bitsPerPixel: 0))
  return try #require(rep.representation(using: .png, properties: [:]))
}

private func temporaryDirectory() -> URL {
  FileManager.default.temporaryDirectory.appending(path: "ripcord-clip-\(UUID().uuidString)")
}

@Suite struct ClipCaptureTests {
  @Test func readsText() {
    withPasteboard { pasteboard in
      pasteboard.declareTypes([.string], owner: nil)
      pasteboard.setString("hello", forType: .string)
      #expect(ClipCapture.read(pasteboard) == .text("hello"))
    }
  }

  @Test func skipsPasswordManagersAndTransientCopies() {
    for marker in [
      "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
      "org.nspasteboard.AutoGeneratedType",
    ] {
      withPasteboard { pasteboard in
        pasteboard.declareTypes([.string, .init(marker)], owner: nil)
        pasteboard.setString("hunter2", forType: .string)
        pasteboard.setData(Data(), forType: .init(marker))
        #expect(ClipCapture.read(pasteboard) == nil)
      }
    }
  }

  @Test func skipsCopiedFilesAndBlankText() {
    withPasteboard { pasteboard in
      pasteboard.writeObjects([URL(fileURLWithPath: "/Applications/Safari.app") as NSURL])
      #expect(ClipCapture.read(pasteboard) == nil)
    }
    withPasteboard { pasteboard in
      pasteboard.declareTypes([.string], owner: nil)
      pasteboard.setString(" \n\t", forType: .string)
      #expect(ClipCapture.read(pasteboard) == nil)
    }
  }

  @Test func skipsTextOverTheCap() {
    withPasteboard { pasteboard in
      pasteboard.declareTypes([.string], owner: nil)
      pasteboard.setString(
        String(repeating: "a", count: ClipCapture.maxTextBytes + 1), forType: .string)
      #expect(ClipCapture.read(pasteboard) == nil)
    }
  }

  @Test func readsAnImageWithItsSize() throws {
    let data = try png(width: 3, height: 2)
    withPasteboard { pasteboard in
      pasteboard.declareTypes([.png], owner: nil)
      pasteboard.setData(data, forType: .png)
      #expect(
        ClipCapture.read(pasteboard) == .image(data, fileExtension: "png", width: 3, height: 2))
    }
  }

  @Test func keepsTheImageWhenItsTextIsBlank() throws {
    let data = try png(width: 3, height: 2)
    withPasteboard { pasteboard in
      pasteboard.declareTypes([.string, .png], owner: nil)
      pasteboard.setString(" ", forType: .string)
      pasteboard.setData(data, forType: .png)
      #expect(
        ClipCapture.read(pasteboard) == .image(data, fileExtension: "png", width: 3, height: 2))
    }
  }

  @Test func keepsACopiedImageFileAsThatImage() throws {
    // CleanShot X copies a capture as its file plus PNG data; Finder copies a file the same way.
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    let file = directory.appending(path: "CleanShot.png")
    let data = try png(width: 5, height: 4)
    try data.write(to: file)
    withPasteboard { pasteboard in
      pasteboard.writeObjects([file as NSURL])
      #expect(
        ClipCapture.read(pasteboard) == .image(data, fileExtension: "png", width: 5, height: 4))
    }
    // A capture whose file is gone still comes through as the PNG copied alongside it.
    let missing = directory.appending(path: "Gone.png")
    withPasteboard { pasteboard in
      pasteboard.writeObjects([missing as NSURL])
      pasteboard.addTypes([.png, .string], owner: nil)
      pasteboard.setData(data, forType: .png)
      pasteboard.setString("Gone.png", forType: .string)
      #expect(
        ClipCapture.read(pasteboard) == .image(data, fileExtension: "png", width: 5, height: 4))
    }
    let notes = directory.appending(path: "notes.txt")
    try Data("hi".utf8).write(to: notes)
    withPasteboard { pasteboard in
      pasteboard.writeObjects([file as NSURL, notes as NSURL])
      #expect(ClipCapture.read(pasteboard) == nil)
    }
  }

  @Test func keepsASpreadsheetCellAsText() throws {
    let data = try png(width: 3, height: 2)
    withPasteboard { pasteboard in
      pasteboard.declareTypes([.string, .png], owner: nil)
      pasteboard.setString("42", forType: .string)
      pasteboard.setData(data, forType: .png)
      #expect(ClipCapture.read(pasteboard) == .text("42"))
    }
  }
}

@Suite struct ClipboardHistoryTests {
  @Test func copyingTheSameTextAgainMovesItUp() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    var history = ClipboardHistory(directory: directory)
    try history.add(.text("a"), at: Date(timeIntervalSince1970: 1))
    try history.add(.text("b"), at: Date(timeIntervalSince1970: 2))
    let first = history.items[1].id
    try history.add(.text("a"), at: Date(timeIntervalSince1970: 3))
    #expect(history.items.map(\.content) == [.text("a"), .text("b")])
    #expect(history.items[0].id == first)
    #expect(history.items[0].date == Date(timeIntervalSince1970: 3))
  }

  @Test func keepsImagesAsFilesAndDeletesThemWithTheirItem() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    var history = ClipboardHistory(directory: directory)
    let data = try png(width: 4, height: 4)
    try history.add(.image(data, fileExtension: "png", width: 4, height: 4))
    let item = try #require(history.items.first)
    let url = try #require(history.imageURL(of: item))
    #expect(try Data(contentsOf: url) == data)
    try history.delete(item.id)
    #expect(history.items.isEmpty)
    #expect(!FileManager.default.fileExists(atPath: url.path))
  }

  @Test func dropsTheOldestUnpinnedItemsPastTheLimit() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    var history = ClipboardHistory(directory: directory)
    try history.add(.text("pinned"))
    try history.togglePin(history.items[0].id)
    let image = try png(width: 1, height: 1)
    try history.add(.image(image, fileExtension: "png", width: 1, height: 1))
    let imageURL = try #require(history.imageURL(of: history.items[0]))
    for index in 0..<ClipboardHistory.limit {
      try history.add(.text("\(index)"))
    }
    #expect(history.items.count == ClipboardHistory.limit + 1)
    #expect(history.items.last?.content == .text("pinned"))
    // The image was the oldest unpinned item, so it alone made room.
    #expect(history.items.contains { $0.content == .text("0") })
    #expect(!history.items.contains { if case .image = $0.content { true } else { false } })
    #expect(!FileManager.default.fileExists(atPath: imageURL.path))
  }

  @Test func countsCopiesAndKeepsWhereAndWhenItWasFirstCopied() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    var history = ClipboardHistory(directory: directory)
    try history.add(.text("a"), at: Date(timeIntervalSince1970: 1), from: "com.apple.Safari")
    try history.add(.text("b"), at: Date(timeIntervalSince1970: 2))
    try history.add(.text("a"), at: Date(timeIntervalSince1970: 3), from: "com.apple.Notes")
    let item = history.items[0]
    #expect(item.content == .text("a"))
    #expect(item.copies == 2)
    #expect(item.source == "com.apple.Safari")
    #expect(item.firstDate == Date(timeIntervalSince1970: 1))
    #expect(item.date == Date(timeIntervalSince1970: 3))
    try history.touch(history.items[1].id, at: Date(timeIntervalSince1970: 4))
    #expect(history.items.map(\.content) == [.text("b"), .text("a")])
    #expect(history.items[0].copies == 2)
  }

  @Test func keepsTheFirstCopyDateOfAnOldItemWhenItIsCopiedAgain() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    let id = UUID()
    let json = """
      [{"id":"\(id.uuidString)","content":{"text":{"_0":"old"}},"digest":"x","date":0,\
      "isPinned":false}]
      """
    try Data(json.utf8).write(to: directory.appending(path: "history.json"))
    var history = ClipboardHistory(directory: directory)
    let first = history.items[0].date
    try history.touch(id, at: first.addingTimeInterval(86_400))
    #expect(history.items[0].firstDate == first)
    #expect(history.items[0].copies == 2)
  }

  @Test func readsAHistoryWrittenBeforeCopyDetailsExisted() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    let id = UUID()
    let json = """
      [{"id":"\(id.uuidString)","content":{"text":{"_0":"old"}},"digest":"x","date":0,\
      "isPinned":true}]
      """
    try Data(json.utf8).write(to: directory.appending(path: "history.json"))
    let item = try #require(ClipboardHistory(directory: directory).items.first)
    #expect(item.id == id && item.isPinned && item.copies == 1 && item.source == nil)
    #expect(item.firstDate == item.date)
  }

  @Test func survivesARelaunch() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    var history = ClipboardHistory(directory: directory)
    try history.add(.text("kept"))
    try history.togglePin(history.items[0].id)
    #expect(ClipboardHistory(directory: directory).items == history.items)
  }

  @Test func movesAnUnreadableFileAsideInsteadOfOverwritingIt() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    try Data("{".utf8).write(to: directory.appending(path: "history.json"))
    #expect(ClipboardHistory(directory: directory).items.isEmpty)
    let names = try FileManager.default.contentsOfDirectory(atPath: directory.path)
    #expect(names.contains { $0.hasPrefix("history-unreadable-") })
    #expect(!names.contains("history.json"))
  }
}

@Suite struct ClipboardSearchTests {
  @Test func listsPinnedFirstThenRecent() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    var history = ClipboardHistory(directory: directory)
    // One fixed instant for adding and grouping, so a run across midnight still says "Today".
    let now = Date(timeIntervalSince1970: 1_000_000)
    try history.add(.text("\n  first line\nsecond line"), at: now)
    try history.add(.text("pin me"), at: now)
    try history.togglePin(history.items[0].id)
    let sections = Search.clipboardSections(for: "", history: history, now: now)
    #expect(sections.map(\.title) == ["Pinned", "Today"])
    #expect(sections[0].results.map(\.title) == ["pin me"])
    #expect(sections[1].results.map(\.title) == ["first line second line"])
  }

  @Test func filtersByTheCopiedTextAndFindsImagesByTheWordImage() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    var history = ClipboardHistory(directory: directory)
    let now = Date(timeIntervalSince1970: 1_000_000)
    try history.add(.text("Hello World"), at: now)
    try history.add(
      .image(try png(width: 2, height: 2), fileExtension: "png", width: 2, height: 2), at: now)
    let found = Search.clipboardSections(for: "world", history: history, now: now)
    #expect(found.map(\.title) == ["Today"])
    #expect(found[0].results.map(\.title) == ["Hello World"])
    let image = try #require(Search.clipboardSections(for: "image", history: history).first)
    #expect(image.results.map(\.subtitle) == ["2×2"])
    #expect(image.results[0].thumbnail != nil)
    #expect(Search.clipboardSections(for: "zzz", history: history).isEmpty)
  }

  @Test func groupsByTheDayItWasLastCopied() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    var calendar = Calendar(identifier: .gregorian)
    calendar.timeZone = try #require(TimeZone(identifier: "UTC"))
    let now = Date(timeIntervalSince1970: 10 * 86_400 + 3_600)
    var history = ClipboardHistory(directory: directory)
    try history.add(.text("last week"), at: now.addingTimeInterval(-7 * 86_400))
    try history.add(.text("yesterday"), at: now.addingTimeInterval(-86_400))
    try history.add(.text("today"), at: now)
    let sections = Search.clipboardSections(
      for: "", history: history, now: now, calendar: calendar)
    #expect(sections.map(\.title) == ["Today", "Yesterday", "Earlier"])
    #expect(sections.map { $0.results.map(\.title) } == [["today"], ["yesterday"], ["last week"]])
  }

  @Test func offersPasteCopyPinAndDelete() throws {
    let directory = temporaryDirectory()
    defer { try? FileManager.default.removeItem(at: directory) }
    var history = ClipboardHistory(directory: directory)
    try history.add(.text("x"))
    let id = history.items[0].id
    let row = try #require(Search.clipboardSections(for: "", history: history).first?.results.first)
    #expect(row.action == .clip(id, .paste))
    #expect(row.actions.map(\.title) == ["Paste to App", "Copy to Clipboard", "Pin", "Delete"])
    #expect(row.actions.map(\.shortcut) == ["↵", "⇧⌘C", "⇧⌘P", "⌃X"])
    try history.togglePin(id)
    let pinned = try #require(
      Search.clipboardSections(for: "", history: history).first?.results.first)
    #expect(pinned.actions[2].title == "Unpin")
  }

  @Test func typingFindsTheCommandButTheStartScreenStaysAsItWas() {
    let results = Search.results(for: "clipboard", apps: [], quicklinks: [])
    #expect(results.first?.action == .run(.clipboardHistory))
    #expect(Search.sections(for: "", apps: [], running: [], quicklinks: []).isEmpty)
  }
}
