import AppKit
import CryptoKit
import UniformTypeIdentifiers

/// One copied piece of text, image or files in the clipboard history.
public struct ClipItem: Codable, Identifiable, Equatable, Sendable {
  public enum Content: Codable, Equatable, Sendable {
    case text(String)
    /// A file in the history's `images` folder.
    case image(file: String, width: Int, height: Int)
    /// Files copied in Finder or another app, by path; the files themselves aren't kept.
    case files([String])
  }

  public let id: UUID
  public let content: Content
  /// SHA-256 of the text or image bytes, so copying the same thing again moves it up instead of
  /// adding it twice.
  public let digest: String
  /// When it was last copied.
  public var date: Date
  public var isPinned: Bool
  // Optional, so a history.json written before these existed still reads.
  /// The bundle ID of the app it was copied in.
  public var source: String?
  public var timesCopied: Int?
  public var firstCopied: Date?
  /// The file name of a copied image file, shown in place of "Image", or of one copied file.
  public var name: String?
  /// An image's size in bytes, or copied files' together.
  public var size: Int?

  public var copies: Int { timesCopied ?? 1 }
  public var firstDate: Date { firstCopied ?? date }
}

/// What the pasteboard held, before it's in the history.
public enum ClipCapture: Equatable, Sendable {
  case text(String)
  case image(Data, fileExtension: String, width: Int, height: Int, name: String? = nil)
  case files([URL])

  /// Text wins over an image, so a spreadsheet cell (offered as both) is kept as its text.
  /// One copied image file, as CleanShot X puts a capture on the pasteboard, is kept as that
  /// image; other copied files are kept by path. Returns nil for what must not be kept:
  /// password managers' concealed or transient copies.
  public static func read(_ pasteboard: NSPasteboard) -> ClipCapture? {
    let types = pasteboard.types ?? []
    let skipped: [NSPasteboard.PasteboardType] = [
      .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
      .init("org.nspasteboard.AutoGeneratedType"),
    ]
    guard !types.contains(where: skipped.contains) else { return nil }
    if types.contains(.fileURL) {
      // The file itself, not the pasteboard's image: for a Finder copy that is the file's icon.
      let urls = pasteboard.readObjects(
        forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true])
      let files = (urls ?? []).compactMap { $0 as? URL }
      guard !files.isEmpty else { return nil }
      guard files.count == 1, let url = files.first,
        UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true
      else { return .files(files) }
      // Size first, so a huge or not-yet-downloaded file is never read on the main thread.
      if let size = try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize,
        size <= maxImageBytes, let data = try? Data(contentsOf: url),
        let capture = image(
          data, fileExtension: url.pathExtension.lowercased(), name: url.lastPathComponent)
      {
        return capture
      }
      // Too big or unreadable: use the image the copying app put alongside, as CleanShot X
      // does, never the file name a Finder copy also carries as text.
      guard
        case .image(let data, let fileExtension, let width, let height, _) =
          pasteboardImage(pasteboard)
      else { return nil }
      return .image(
        data, fileExtension: fileExtension, width: width, height: height,
        name: url.lastPathComponent)
    }
    // shortcut: a fixed cap keeps history.json small; becomes a setting with #5.
    if let text = pasteboard.string(forType: .string),
      !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
      text.utf8.count <= maxTextBytes
    {
      return .text(text)
    }
    return pasteboardImage(pasteboard)
  }

  /// PNG first: a screenshot's TIFF can be ten times its size.
  private static func pasteboardImage(_ pasteboard: NSPasteboard) -> ClipCapture? {
    for (type, fileExtension) in [(NSPasteboard.PasteboardType.png, "png"), (.tiff, "tiff")] {
      if let data = pasteboard.data(forType: type),
        let capture = image(data, fileExtension: fileExtension)
      {
        return capture
      }
    }
    return nil
  }

  private static func image(_ data: Data, fileExtension: String, name: String? = nil)
    -> ClipCapture?
  {
    guard data.count <= maxImageBytes,
      let source = CGImageSourceCreateWithData(data as CFData, nil),
      // Decoded lazily: reading the size doesn't unpack the pixels.
      let image = CGImageSourceCreateImageAtIndex(source, 0, nil)
    else { return nil }
    return .image(
      data, fileExtension: fileExtension, width: image.width, height: image.height, name: name)
  }

  /// The app that says it made the copy, by the nspasteboard.org convention; few apps do.
  public static func source(_ pasteboard: NSPasteboard) -> String? {
    pasteboard.string(forType: .init("org.nspasteboard.source")).flatMap { $0.isEmpty ? nil : $0 }
  }

  static let maxTextBytes = 1 << 20
  static let maxImageBytes = 32 << 20

  var digest: String {
    let bytes =
      switch self {
      case .text(let text): Data(text.utf8)
      case .image(let data, _, _, _, _): data
      // Marked, so a file and its path copied as text stay two items.
      case .files(let urls): Data((["files"] + urls.map(\.path)).joined(separator: "\n").utf8)
      }
    return SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined()
  }
}

/// The clipboard history: `history.json` plus an `images` folder, newest first.
public struct ClipboardHistory: Sendable {
  public private(set) var items: [ClipItem] = []
  public let directory: URL
  /// Unpinned items beyond this are dropped, oldest first.
  // shortcut: a fixed count until #5 adds retention settings.
  public static let limit = 300

  private var fileURL: URL { directory.appending(path: "history.json") }
  public var imagesURL: URL { directory.appending(path: "images") }

  /// Reads the history in `directory`, or starts empty. A file that can't be read is moved
  /// aside rather than overwritten by the next copy.
  public init(directory: URL) {
    self.directory = directory
    guard let data = try? Data(contentsOf: fileURL) else { return }
    do {
      items = try JSONDecoder().decode([ClipItem].self, from: data)
    } catch {
      try? FileManager.default.moveItem(
        at: fileURL, to: directory.appending(path: "history-unreadable-\(UUID().uuidString).json"))
    }
  }

  /// Puts `capture` first, reusing the entry when the same text or image is already kept.
  // shortcut: hashing and saving run on the caller's (main) thread, a few ms for a screenshot;
  // move them off it if huge images or texts make copying stutter.
  public mutating func add(_ capture: ClipCapture, at date: Date = .now, from source: String? = nil)
    throws
  {
    let digest = capture.digest
    let name: String?
    let size: Int?
    switch capture {
    case .image(let data, _, _, _, let fileName): (name, size) = (fileName, data.count)
    case .files(let urls):
      // Read from the file system's records, not the files, so a big one costs nothing. A
      // folder or an app's record isn't the size of what's in it, so then there's none.
      let values = urls.map {
        try? $0.resourceValues(forKeys: [.isDirectoryKey, .totalFileSizeKey, .fileSizeKey])
      }
      let sizes = values.compactMap { value in
        value?.isDirectory == false ? value?.totalFileSize ?? value?.fileSize : nil
      }
      (name, size) = (
        urls.count == 1 ? urls[0].lastPathComponent : nil,
        sizes.count == urls.count ? sizes.reduce(0, +) : nil
      )
    case .text: (name, size) = (nil, nil)
    }
    if let item = items.first(where: { $0.digest == digest }) {
      return try touch(item.id, at: date, name: name)
    }
    let id = UUID()
    let content: ClipItem.Content
    switch capture {
    case .text(let text):
      content = .text(text)
    case .image(let data, let fileExtension, let width, let height, _):
      let file = "\(id.uuidString).\(fileExtension)"
      try FileManager.default.createDirectory(at: imagesURL, withIntermediateDirectories: true)
      try data.write(to: imagesURL.appending(path: file), options: .atomic)
      content = .image(file: file, width: width, height: height)
    case .files(let urls):
      content = .files(urls.map(\.path))
    }
    let added = [
      ClipItem(
        id: id, content: content, digest: digest, date: date, isPinned: false, source: source,
        timesCopied: 1, firstCopied: date, name: name, size: size)
    ]
    let dropped = Set((added + items).filter { !$0.isPinned }.dropFirst(Self.limit).map(\.id))
    items = (added + items).filter { item in
      guard dropped.contains(item.id) else { return true }
      removeFile(of: item)
      return false
    }
    try save()
  }

  /// Counts another copy of `id` and moves it to the top; a copied file's `name` renames it.
  public mutating func touch(_ id: UUID, at date: Date = .now, name: String? = nil) throws {
    guard var item = item(id) else { return }
    item.name = name ?? item.name
    // Kept before `date` moves on, for items saved before firstCopied existed.
    item.firstCopied = item.firstDate
    item.date = date
    item.timesCopied = item.copies + 1
    items = [item] + items.filter { $0.id != id }
    try save()
  }

  public mutating func togglePin(_ id: UUID) throws {
    guard let index = items.firstIndex(where: { $0.id == id }) else { return }
    items[index].isPinned.toggle()
    try save()
  }

  public mutating func delete(_ id: UUID) throws {
    guard let item = item(id) else { return }
    removeFile(of: item)
    items = items.filter { $0.id != id }
    try save()
  }

  public func item(_ id: UUID) -> ClipItem? {
    items.first { $0.id == id }
  }

  /// The image file behind `item`, nil for text.
  public func imageURL(of item: ClipItem) -> URL? {
    guard case .image(let file, _, _) = item.content else { return nil }
    return imagesURL.appending(path: file)
  }

  private func removeFile(of item: ClipItem) {
    if let url = imageURL(of: item) { try? FileManager.default.removeItem(at: url) }
  }

  private func save() throws {
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    try JSONEncoder().encode(items).write(to: fileURL, options: .atomic)
  }
}
