import AppKit
import CryptoKit

/// One copied piece of text or image in the clipboard history.
public struct ClipItem: Codable, Identifiable, Equatable, Sendable {
  public enum Content: Codable, Equatable, Sendable {
    case text(String)
    /// A file in the history's `images` folder.
    case image(file: String, width: Int, height: Int)
  }

  public let id: UUID
  public let content: Content
  /// SHA-256 of the text or image bytes, so copying the same thing again moves it up instead of
  /// adding it twice.
  public let digest: String
  public var date: Date
  public var isPinned: Bool
}

/// What the pasteboard held, before it's in the history.
public enum ClipCapture: Equatable, Sendable {
  case text(String)
  case image(Data, fileExtension: String, width: Int, height: Int)

  /// Text wins over an image, so a spreadsheet cell (offered as both) is kept as its text.
  /// Returns nil for what must not be kept: password managers' concealed or transient copies,
  /// and copied files (#4).
  public static func read(_ pasteboard: NSPasteboard) -> ClipCapture? {
    let types = pasteboard.types ?? []
    let skipped: [NSPasteboard.PasteboardType] = [
      .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
      .init("org.nspasteboard.AutoGeneratedType"), .fileURL,
    ]
    guard !types.contains(where: skipped.contains) else { return nil }
    // shortcut: a fixed cap keeps history.json small; becomes a setting with #5.
    if let text = pasteboard.string(forType: .string),
      !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
      text.utf8.count <= maxTextBytes
    {
      return .text(text)
    }
    // PNG first: a screenshot's TIFF can be ten times its size.
    for (type, fileExtension) in [(NSPasteboard.PasteboardType.png, "png"), (.tiff, "tiff")] {
      guard let data = pasteboard.data(forType: type), data.count <= maxImageBytes,
        let source = CGImageSourceCreateWithData(data as CFData, nil),
        // Decoded lazily: reading the size doesn't unpack the pixels.
        let image = CGImageSourceCreateImageAtIndex(source, 0, nil)
      else { continue }
      return .image(data, fileExtension: fileExtension, width: image.width, height: image.height)
    }
    return nil
  }

  static let maxTextBytes = 1 << 20
  static let maxImageBytes = 32 << 20

  var digest: String {
    let bytes =
      switch self {
      case .text(let text): Data(text.utf8)
      case .image(let data, _, _, _): data
      }
    return SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined()
  }
}

/// The clipboard history: `history.json` plus an `images` folder, newest first.
public struct ClipboardHistory: Sendable {
  public private(set) var items: [ClipItem] = []
  public let directory: URL
  /// Unpinned items beyond this are dropped, oldest first.
  // shortcut: a fixed count until #5 adds retention settings.
  public static let limit = 300

  private var fileURL: URL { directory.appending(path: "history.json") }
  public var imagesURL: URL { directory.appending(path: "images") }

  /// Reads the history in `directory`, or starts empty. A file that can't be read is moved
  /// aside rather than overwritten by the next copy.
  public init(directory: URL) {
    self.directory = directory
    guard let data = try? Data(contentsOf: fileURL) else { return }
    do {
      items = try JSONDecoder().decode([ClipItem].self, from: data)
    } catch {
      try? FileManager.default.moveItem(
        at: fileURL, to: directory.appending(path: "history-unreadable-\(UUID().uuidString).json"))
    }
  }

  /// Puts `capture` first, reusing the entry when the same text or image is already kept.
  // shortcut: hashing and saving run on the caller's (main) thread, a few ms for a screenshot;
  // move them off it if huge images or texts make copying stutter.
  public mutating func add(_ capture: ClipCapture, at date: Date = .now) throws {
    let digest = capture.digest
    if var item = items.first(where: { $0.digest == digest }) {
      item.date = date
      items = [item] + items.filter { $0.id != item.id }
      return try save()
    }
    let id = UUID()
    let content: ClipItem.Content
    switch capture {
    case .text(let text):
      content = .text(text)
    case .image(let data, let fileExtension, let width, let height):
      let file = "\(id.uuidString).\(fileExtension)"
      try FileManager.default.createDirectory(at: imagesURL, withIntermediateDirectories: true)
      try data.write(to: imagesURL.appending(path: file), options: .atomic)
      content = .image(file: file, width: width, height: height)
    }
    let added = [ClipItem(id: id, content: content, digest: digest, date: date, isPinned: false)]
    let dropped = Set((added + items).filter { !$0.isPinned }.dropFirst(Self.limit).map(\.id))
    items = (added + items).filter { item in
      guard dropped.contains(item.id) else { return true }
      removeFile(of: item)
      return false
    }
    try save()
  }

  public mutating func togglePin(_ id: UUID) throws {
    guard let index = items.firstIndex(where: { $0.id == id }) else { return }
    items[index].isPinned.toggle()
    try save()
  }

  public mutating func delete(_ id: UUID) throws {
    guard let item = item(id) else { return }
    removeFile(of: item)
    items = items.filter { $0.id != id }
    try save()
  }

  public func item(_ id: UUID) -> ClipItem? {
    items.first { $0.id == id }
  }

  /// The image file behind `item`, nil for text.
  public func imageURL(of item: ClipItem) -> URL? {
    guard case .image(let file, _, _) = item.content else { return nil }
    return imagesURL.appending(path: file)
  }

  private func removeFile(of item: ClipItem) {
    if let url = imageURL(of: item) { try? FileManager.default.removeItem(at: url) }
  }

  private func save() throws {
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    try JSONEncoder().encode(items).write(to: fileURL, options: .atomic)
  }
}
